"""Stage 8 ``report``: assemble ``build/report.md``. ``python -m mcarisk.report`` / ``make report``.

The report is an index, not a new analysis. It links the generated documents (findings, model card,
data-quality report, latest eval report), quotes the headline numbers from the findings registry
(``build/findings_numbers.json``: every value there is a metric-table query re-checked by
``check_findings``), and summarises the run manifest and the ``data_quality`` table. It defines no metric.

The eval summary is read from ``evals/reports/latest.json`` when it exists. ``make all`` runs before
``make eval``, so the summary describes the *last* eval run (its timestamp and git SHA are printed).
"""

from __future__ import annotations

import argparse
import json
import os
import string
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import duckdb

from mcarisk import paths
from mcarisk.manifest import RunManifest, StageRecorder, open_run

REPORT_MD = paths.BUILD_DIR / "report.md"
EVAL_LATEST = paths.ROOT / "evals" / "reports" / "latest.json"

# Findings-registry keys quoted in the headline, in order, with the sentence they fill.
HEADLINE: list[tuple[str, str]] = [
    ("Reported vs cash-based collection rate (closed deals, RTR-weighted)", "{p1_rep} vs {p1_adj}"),
    ("Renewal masking gap", "{p2_gap}"),
    ("Internal-payoff share of reported collections", "{p3_share}"),
    ("Bad rate naive vs economic, closed deals (n = {p4_closed_n})", "{p4_naive} vs {p4_econ}"),
    (
        "T1 economic vs naive bad rate within 180 business days ({t1_mature_n} mature deals)",
        "{t1_econ} vs {t1_naive}",
    ),
    ("Open exposure: economic vs contractual ({p6_open_n} open relationships)", "{p6_econ} vs {p6_contr}"),
    ("Distressed share of renewals", "{p8_share} ({p8_share_k} of {p8_share_n})"),
    ("Resolved chains ending in loss, with vs without a distressed refinance", "{p8_with} vs {p8_without}"),
    ("Modification cure rate", "{p9_all}"),
]


@dataclass
class ReportResult:
    path: Path
    sections: list[str]
    eval_overall: str | None
    seconds: float


def _rel(p: Path, base: Path) -> str:
    try:
        return Path(os.path.relpath(Path(p).resolve(), Path(base).resolve())).as_posix()
    except ValueError:  # different drives on Windows
        return Path(p).as_posix()


def _load_json(p: Path) -> Any:
    return json.loads(Path(p).read_text(encoding="utf-8")) if Path(p).exists() else None


def _headline(numbers: list[dict[str, Any]]) -> list[str]:
    by_key = {n["key"]: n for n in numbers}
    lines = []
    for label, tmpl in HEADLINE:
        keys = _placeholders(label + tmpl)
        if any(k not in by_key for k in keys):
            continue
        texts = {k: by_key[k]["text"] for k in keys}
        ids = sorted({i for k in keys for i in by_key[k]["metric_ids"]})
        lines.append(f"- {label.format(**texts)}: **{tmpl.format(**texts)}** ({', '.join(ids)})")
    return lines


def _placeholders(s: str) -> list[str]:
    return [f for _, f, _, _ in string.Formatter().parse(s) if f]


def build_report(
    build_dir: Path = paths.BUILD_DIR,
    *,
    report_md: Path | None = None,
    eval_latest: Path = EVAL_LATEST,
    run: RunManifest | None = None,
) -> ReportResult:
    t0 = time.perf_counter()
    build_dir = Path(build_dir)
    report_md = Path(report_md) if report_md else build_dir / "report.md"
    manifest = _load_json(build_dir / "run_manifest.json") or {}
    numbers = _load_json(build_dir / "findings_numbers.json") or []
    ev = _load_json(eval_latest)

    con = duckdb.connect(str(build_dir / "portfolio.duckdb"), read_only=True)
    try:
        as_of = con.execute("SELECT MAX(as_of) FROM portfolio_metrics").fetchone()[0]
        dq = con.execute(
            "SELECT rule_id, rule, hits, denominator FROM data_quality ORDER BY rule_id"
        ).fetchall()
        n_exc = con.execute("SELECT COUNT(*) FROM exceptions").fetchone()[0]
    finally:
        con.close()

    git = manifest.get("git", {})
    out: list[str] = [
        "# MCA portfolio risk: run report",
        "",
        f"As of **{as_of}**, METRICS.md {manifest.get('metrics_md', {}).get('version', '?')}. "
        f"Run `{manifest.get('run_id', '?')}`, git `{(git.get('sha') or 'uncommitted')[:12]}`"
        f"{' (dirty)' if git.get('dirty') else ''}. Generated by `make report`; do not edit by hand.",
        "",
        "## Documents",
        "",
    ]
    docs = [
        (
            "Findings",
            build_dir / "findings.md",
            "portfolio analytics; every number is a registered metric-table query",
        ),
        ("Model card", build_dir / "model_card.md", "T1 / T2 / T3 models, calibration, limitations"),
        (
            "Data-quality report",
            build_dir / "dq_report.md",
            "rule hits Q1-Q7, L1-L3, S1-S6 and the exceptions queue",
        ),
        ("Run manifest", build_dir / "run_manifest.json", "input hashes, stage timings, row accounting"),
        ("Figures", build_dir / "figures", "PNG, interactive plotly JSON and data CSV per figure"),
    ]
    for name, p, what in docs:
        status = "" if Path(p).exists() else " (missing)"
        out.append(f"- [{name}]({_rel(p, report_md.parent)}){status}: {what}")
    if ev is not None:
        out.append(
            f"- [Eval report]({_rel(Path(eval_latest).with_suffix('.md'), report_md.parent)}): latest `make eval`"
        )
    out += ["", "## Headline (from the findings registry)", ""]
    out += _headline(numbers) or ["- findings registry not found; run `make analytics`"]

    out += ["", "## Pipeline stages", "", "| Stage | Status | Seconds |", "|---|---|---:|"]
    for name, st in manifest.get("stages", {}).items():
        out.append(f"| {name} | {st.get('status')} | {st.get('seconds')} |")

    out += [
        "",
        f"## Data quality ({n_exc} exceptions queued for review)",
        "",
        "| Rule | What | Hits | Of |",
        "|---|---|---:|---:|",
    ]
    for rid, rule, hits, den in dq:
        out.append(
            f"| {rid} | {rule} | {'' if hits is None else f'{hits:,}'} | {'' if den is None else f'{den:,}'} |"
        )

    out += ["", "## Evals", ""]
    if ev is None:
        out.append("No eval report yet: run `make eval`.")
    else:
        out.append(
            f"Last `make eval`: `{ev.get('timestamp')}` on git `{(ev.get('git_sha') or '?')[:12]}`, "
            f"overall **{ev.get('overall')}**. Gates: `evals/thresholds.json`."
        )
        out += ["", "| Suite | Name | Status | Gated metrics |", "|---|---|---|---|"]
        for s in ev.get("suites", []):
            gates = ", ".join(
                f"{k} = {_fmt(g.get('value'))} ({g.get('op')} {_fmt(g.get('target'))})"
                for k, g in (s.get("gates") or {}).items()
            )
            out.append(f"| {s.get('suite')} | {s.get('name')} | {s.get('status')} | {gates} |")
    out.append("")

    report_md.parent.mkdir(parents=True, exist_ok=True)
    report_md.write_text("\n".join(out), encoding="utf-8", newline="\n")
    sections = [line[3:] for line in out if line.startswith("## ")]
    res = ReportResult(
        report_md, sections, ev.get("overall") if ev else None, round(time.perf_counter() - t0, 3)
    )
    if run is not None:
        st = StageRecorder(run.data["stages"]["report"])
        st.extra(
            "report", {"path": report_md.as_posix(), "sections": sections, "eval_overall": res.eval_overall}
        )
    return res


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.4g}"
    if isinstance(v, list):
        return "[" + ", ".join(_fmt(x) for x in v) + "]"
    return str(v)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Assemble build/report.md (Part 7).")
    ap.add_argument("--build", type=Path, default=paths.BUILD_DIR)
    ap.add_argument("--manifest", type=Path, default=None)
    args = ap.parse_args(argv)
    if not (args.build / "portfolio.duckdb").exists():
        print(f"[report] {args.build / 'portfolio.duckdb'} not found; run `make all` first", file=sys.stderr)
        return 1
    run = open_run(args.manifest or args.build / "run_manifest.json")
    with run.stage("report"):
        res = build_report(args.build, run=run)
    print(f"[report] done in {res.seconds:.2f}s -> {res.path} (eval overall: {res.eval_overall})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
